from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument('stm_ip', default_value='192.168.0.4', description='STM32 Nucleo IP address'),
        DeclareLaunchArgument('stm_port', default_value='2002', description='STM32 UDP port'),
        DeclareLaunchArgument('local_port', default_value='2023', description='Local UDP bind port'),
        DeclareLaunchArgument('local_ip', default_value='', description='Local bind IP (empty for ANY interface)'),
        DeclareLaunchArgument('loop_hz', default_value='33.33', description='Control loop frequency (Hz)'),
        DeclareLaunchArgument('rpm_max', default_value='428.0', description='Maximum motor RPM'),
        DeclareLaunchArgument('pwm_max', default_value='225.0', description='Maximum PWM value'),
        DeclareLaunchArgument('pwm_scale', default_value='0.932', description='PWM calibration scale factor'),
        DeclareLaunchArgument('odom_frame', default_value='odom', description='Odometry frame ID'),
        DeclareLaunchArgument('base_frame', default_value='base_footprint', description='Robot base frame ID'),
        DeclareLaunchArgument('yaw_offset_deg', default_value='0.0', description='IMU yaw offset in degrees'),
        DeclareLaunchArgument('use_yaw_topic', default_value='true', description='Use external /vision/yaw_deg instead of STM32 yaw'),
        DeclareLaunchArgument('yaw_topic', default_value='/vision/yaw_deg', description='External yaw topic name'),
        DeclareLaunchArgument('yaw_topic_timeout', default_value='0.5', description='External yaw timeout (seconds)'),
        DeclareLaunchArgument('cmd_vel_timeout', default_value='0.5', description='Command velocity timeout (seconds)'),
        DeclareLaunchArgument('joy_topic', default_value='joy_vel', description='Joystick override velocity topic'),
        DeclareLaunchArgument('test_topic', default_value='test_vel', description='Manual test velocity topic'),
        DeclareLaunchArgument('lifter_cmd_topic', default_value='lifter_target', description='Lifter command topic (0: down, 1: up)'),
        DeclareLaunchArgument('lifter_state_topic', default_value='lifter_state', description='Lifter state feedback topic'),
        DeclareLaunchArgument('smoothing_enable', default_value='true', description='Enable acceleration slew-rate smoothing'),
        DeclareLaunchArgument('linear_accel_limit', default_value='2.5', description='Linear acceleration limit (m/s^2)'),
        DeclareLaunchArgument('angular_accel_limit', default_value='7.0', description='Angular acceleration limit (rad/s^2)'),
        DeclareLaunchArgument('stop_decel_scale', default_value='2.0', description='Stop deceleration multiplier'),
        DeclareLaunchArgument('pulses_per_rev', default_value='7500.0', description='Encoder pulses per wheel revolution'),
        DeclareLaunchArgument('wheel_radius_cm', default_value='5.0', description='Wheel radius (cm)'),
        DeclareLaunchArgument('base_length_cm', default_value='20.8', description='Base distance between wheels (cm)'),

        Node(
            package='athome_base',
            executable='nucleo',
            output='screen',
            parameters=[{
                'stm_ip': LaunchConfiguration('stm_ip'),
                'stm_port': LaunchConfiguration('stm_port'),
                'local_port': LaunchConfiguration('local_port'),
                'local_ip': LaunchConfiguration('local_ip'),
                'loop_hz': LaunchConfiguration('loop_hz'),
                'rpm_max': LaunchConfiguration('rpm_max'),
                'pwm_max': LaunchConfiguration('pwm_max'),
                'pwm_scale': LaunchConfiguration('pwm_scale'),
                'odom_frame': LaunchConfiguration('odom_frame'),
                'base_frame': LaunchConfiguration('base_frame'),
                'yaw_offset_deg': LaunchConfiguration('yaw_offset_deg'),
                'use_yaw_topic': LaunchConfiguration('use_yaw_topic'),
                'yaw_topic': LaunchConfiguration('yaw_topic'),
                'yaw_topic_timeout': LaunchConfiguration('yaw_topic_timeout'),
                'cmd_vel_timeout': LaunchConfiguration('cmd_vel_timeout'),
                'joy_topic': LaunchConfiguration('joy_topic'),
                'test_topic': LaunchConfiguration('test_topic'),
                'lifter_cmd_topic': LaunchConfiguration('lifter_cmd_topic'),
                'lifter_state_topic': LaunchConfiguration('lifter_state_topic'),
                'smoothing_enable': LaunchConfiguration('smoothing_enable'),
                'linear_accel_limit': LaunchConfiguration('linear_accel_limit'),
                'angular_accel_limit': LaunchConfiguration('angular_accel_limit'),
                'stop_decel_scale': LaunchConfiguration('stop_decel_scale'),
                'pulses_per_rev': LaunchConfiguration('pulses_per_rev'),
                'wheel_radius_cm': LaunchConfiguration('wheel_radius_cm'),
                'base_length_cm': LaunchConfiguration('base_length_cm'),
            }],
        ),
    ])
