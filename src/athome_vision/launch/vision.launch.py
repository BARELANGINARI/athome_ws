import os
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, SetEnvironmentVariable
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def generate_launch_description():
    pkg_vision = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
    default_params_file = os.path.join(pkg_vision, 'config', 'vision_params.yaml')

    return LaunchDescription([
        SetEnvironmentVariable('RCUTILS_CONSOLE_OUTPUT_FORMAT', '[{severity}] {message}'),
        DeclareLaunchArgument('params_file', default_value=default_params_file, description='Path to vision ROS 2 parameters YAML file'),
        DeclareLaunchArgument('task', default_value='all', description='Task filter for vision logging: help_me_carry, receptionist, restaurant, or all'),
        DeclareLaunchArgument('camera_fps', default_value='30.0', description='Camera frame rate (FPS)'),
        DeclareLaunchArgument('camera_resolution', default_value='', description='ZED camera resolution override: vga, hd720, hd1080, hd2k (default empty to use YAML or task default)'),
        DeclareLaunchArgument('publish_yaw', default_value='true', description='Publish IMU yaw topic'),
        DeclareLaunchArgument('yaw_360', default_value='true', description='Publish IMU yaw in 0-360 range instead of -180..180'),
        DeclareLaunchArgument('depth_minimum_distance', default_value='30.0', description='Minimum depth sensing distance (cm)'),
        DeclareLaunchArgument('enable_body_tracking', default_value='true', description='Enable ZED body tracking'),
        DeclareLaunchArgument('enable_yolo', default_value='true', description='Enable YOLO object detection'),
        DeclareLaunchArgument('debug_window', default_value='false', description='Show OpenCV preview window'),
        DeclareLaunchArgument('mirror', default_value='true', description='Mirror display preview horizontally'),
        DeclareLaunchArgument('yolo_model', default_value='models/paper_bag.onnx', description='Path to YOLO ONNX model'),
        DeclareLaunchArgument('yolo_classes', default_value='models/paper_bag_classes.txt', description='Path to YOLO class labels file'),
        DeclareLaunchArgument('yolo_conf', default_value='0.35', description='YOLO confidence threshold'),
        DeclareLaunchArgument('bag_conf', default_value='0.35', description='Bag detection confidence threshold'),
        DeclareLaunchArgument('yolo_nms', default_value='0.45', description='YOLO NMS IoU threshold'),
        DeclareLaunchArgument('yolo_size', default_value='640', description='YOLO input image dimension'),
        DeclareLaunchArgument('yolo_min_area', default_value='250.0', description='Minimum bounding box area (pixels)'),
        DeclareLaunchArgument('face_detect_model', default_value='models/face_detection_yunet.onnx', description='Path to YuNet face detection ONNX model'),
        DeclareLaunchArgument('face_detect_conf', default_value='0.55', description='Confidence threshold for YuNet face detector'),
        DeclareLaunchArgument('gender_model', default_value='models/genderage.onnx', description='Path to gender ONNX model'),
        DeclareLaunchArgument('color_model', default_value='models/color_model.onnx', description='Path to clothing color ONNX model'),
        DeclareLaunchArgument('color_labels', default_value='models/color_names.txt', description='Path to clothing color labels file'),
        DeclareLaunchArgument('hair_model', default_value='models/hair_model.onnx', description='Path to hair color ONNX model'),
        DeclareLaunchArgument('hair_labels', default_value='models/hair_names.txt', description='Path to hair labels file'),
        DeclareLaunchArgument('face_model', default_value='models/face_recognition_sface.onnx', description='Path to face recognition ONNX model'),
        DeclareLaunchArgument('face_threshold', default_value='0.363', description='Cosine similarity threshold for face recognition match'),
        DeclareLaunchArgument('botol_model', default_value='models/water.onnx', description='Path to water/botol ONNX model'),
        DeclareLaunchArgument('soda_model', default_value='models/soda.onnx', description='Path to soda ONNX model'),
        DeclareLaunchArgument('cracker_model', default_value='models/crackerbox.onnx', description='Path to cheezit/cracker ONNX model'),
        DeclareLaunchArgument('pringles_model', default_value='models/pringles.onnx', description='Path to pringles ONNX model'),
        DeclareLaunchArgument('sugarbox_model', default_value='models/sugarbox.onnx', description='Path to sugarbox ONNX model'),
        DeclareLaunchArgument('milk_model', default_value='models/milk.onnx', description='Path to milk ONNX model'),
        DeclareLaunchArgument('drink_min_area', default_value='180.0', description='Minimum bounding box area for drinks & crackers (pixels)'),
        DeclareLaunchArgument('drink_conf', default_value='0.48', description='Confidence threshold for drinks & crackers'),
        DeclareLaunchArgument('water_conf', default_value='0.25', description='Confidence threshold for water bottle detection'),
        DeclareLaunchArgument('drink_max_dist', default_value='2.5', description='Maximum distance (m) to detect drinks & crackers'),
        DeclareLaunchArgument('enable_drinks', default_value='true', description='Enable bottle & cracker detection for receptionist'),
        DeclareLaunchArgument('chair_model', default_value='', description='Optional path to custom chair ONNX model'),
        DeclareLaunchArgument('enable_chair', default_value='true', description='Enable chair detection and empty/occupied classification'),
        DeclareLaunchArgument('enable_bag', default_value='true', description='Enable luggage bag detection (for Help Me Carry)'),
        DeclareLaunchArgument('host_name', default_value='Revaldo', description='Default host name for pre-registration'),
        DeclareLaunchArgument('host_photo', default_value='models/host.jpg', description='Optional photo of the host to pre-register face'),
        DeclareLaunchArgument('host_shirt_color', default_value='black shirt', description='Default host shirt color'),
        DeclareLaunchArgument('host_gender', default_value='male', description='Default host gender'),
        DeclareLaunchArgument('host_hair_color', default_value='black', description='Default host hair color'),
        DeclareLaunchArgument('enable_back_detection', default_value='true', description='Enable person facing back detection'),
        DeclareLaunchArgument('person_back_topic', default_value='/vision/person_back', description='Topic for person facing back coordinates'),
        DeclareLaunchArgument('person_max_dist', default_value='1.5', description='Maximum distance (m) to detect and bbox person'),
        DeclareLaunchArgument('bag_max_dist', default_value='2.5', description='Maximum distance (m) to detect and bbox bag'),

        Node(
            package='athome_vision',
            executable='vision',
            name='vision',
            output='screen',
            respawn=True,
            respawn_delay=2.0,
            parameters=[
                LaunchConfiguration('params_file'),
                {
                    'task': LaunchConfiguration('task'),
                    'camera_fps': LaunchConfiguration('camera_fps'),
                    'publish_yaw': LaunchConfiguration('publish_yaw'),
                    'yaw_360': LaunchConfiguration('yaw_360'),
                    'depth_minimum_distance': LaunchConfiguration('depth_minimum_distance'),
                    'enable_body_tracking': LaunchConfiguration('enable_body_tracking'),
                    'enable_yolo': LaunchConfiguration('enable_yolo'),
                    'debug_window': LaunchConfiguration('debug_window'),
                    'mirror': LaunchConfiguration('mirror'),
                    'yolo_model': LaunchConfiguration('yolo_model'),
                    'yolo_classes': LaunchConfiguration('yolo_classes'),
                    'yolo_conf': LaunchConfiguration('yolo_conf'),
                    'bag_conf': LaunchConfiguration('bag_conf'),
                    'yolo_nms': LaunchConfiguration('yolo_nms'),
                    'yolo_size': LaunchConfiguration('yolo_size'),
                    'yolo_min_area': LaunchConfiguration('yolo_min_area'),
                    'face_detect_model': LaunchConfiguration('face_detect_model'),
                    'face_detect_conf': LaunchConfiguration('face_detect_conf'),
                    'gender_model': LaunchConfiguration('gender_model'),
                    'color_model': LaunchConfiguration('color_model'),
                    'color_labels': LaunchConfiguration('color_labels'),
                    'hair_model': LaunchConfiguration('hair_model'),
                    'hair_labels': LaunchConfiguration('hair_labels'),
                    'face_model': LaunchConfiguration('face_model'),
                    'face_threshold': LaunchConfiguration('face_threshold'),
                    'botol_model': LaunchConfiguration('botol_model'),
                    'soda_model': LaunchConfiguration('soda_model'),
                    'cracker_model': LaunchConfiguration('cracker_model'),
                    'pringles_model': LaunchConfiguration('pringles_model'),
                    'sugarbox_model': LaunchConfiguration('sugarbox_model'),
                    'milk_model': LaunchConfiguration('milk_model'),
                    'drink_min_area': LaunchConfiguration('drink_min_area'),
                    'drink_conf': LaunchConfiguration('drink_conf'),
                    'water_conf': LaunchConfiguration('water_conf'),
                    'drink_max_dist': LaunchConfiguration('drink_max_dist'),
                    'enable_drinks': LaunchConfiguration('enable_drinks'),
                    'chair_model': LaunchConfiguration('chair_model'),
                    'enable_chair': LaunchConfiguration('enable_chair'),
                    'enable_bag': LaunchConfiguration('enable_bag'),
                    'enable_back_detection': LaunchConfiguration('enable_back_detection'),
                    'person_back_topic': LaunchConfiguration('person_back_topic'),
                    'person_max_dist': LaunchConfiguration('person_max_dist'),
                    'bag_max_dist': LaunchConfiguration('bag_max_dist'),
                },
            ],
        ),
    ])
